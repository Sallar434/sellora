"""Locale, setup, import guard, bulk undo, health, insights, and payment honesty."""
import os
from playwright.sync_api import sync_playwright

F = 'file://' + os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'sellora.html'))
R = []

def ok(n, c, d=''):
    R.append(bool(c))
    print(('PASS ' if c else 'FAIL ') + n + ((' :: ' + str(d)[:400]) if d and not c else ''), flush=True)

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={'width': 1280, 'height': 800})
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)[:300]))
    pg.goto(F)
    pg.wait_for_timeout(600)
    pg.click('#door-up')
    pg.fill('#a2', 'setup18@example.com')
    pg.fill('#a3', 'password123')
    pg.click('#ab')
    pg.wait_for_timeout(300)
    pg.click('[data-m13p=grow]')
    pg.wait_for_timeout(200)
    pg.fill('#a1', 'Setup Shop')
    pg.click('#ab')
    pg.wait_for_timeout(800)
    ok('next step names one real blocker', pg.locator('#m17step').get_attribute('data-step') in ('addProduct', 'finishListing', 'launch', 'payment'))
    ok('home does not invent sessions', 'Sessions' not in pg.inner_text('#main') and 'Conversion rate' not in pg.inner_text('#main'))
    pg.evaluate("SelloraPlatform && (S.locale='ur'); save();")
    pg.evaluate("location.hash='setup'")
    pg.wait_for_timeout(400)
    ok('urdu is rtl and the phrase is translated', pg.evaluate("document.documentElement.dir")=='rtl' and pg.locator('#m17step').get_attribute('data-status')=='translated')
    pg.reload()
    pg.wait_for_timeout(800)
    ok('locale survives reload', pg.evaluate("S.locale")=='ur' and pg.evaluate("document.documentElement.dir")=='rtl')
    pg.evaluate("S.locale='en'; save();")
    escaped = pg.evaluate("""(() => { var rec=SelloraPlatform.draftTranslation({id:'t1',entity:'product',entityId:'1',locale:'ar',original:'Sellora mug',fields:{body:'<script>alert(1)</script> Sellora'},brandNames:['Sellora'],provider:'manual',providerText:null}); return {ok:rec.ok, html:SelloraPlatform.escapeHtml(rec.ok?rec.record.fields.body:'')}; })()""")
    ok('manual translation keeps the brand and escapes markup', escaped['ok'] and '&lt;script&gt;' in escaped['html'])
    blocked = pg.evaluate("SelloraPlatform.draftTranslation({id:'t2',entity:'product',entityId:'1',locale:'ar',original:'Sellora',fields:{},brandNames:['Sellora'],provider:'deepseek',providerText:null})")
    ok('missing provider is not a translation', blocked['ok'] is False and blocked.get('blocked')=='missing-provider')
    voice = pg.evaluate("new Promise(function(res){AIBuild.voiceListen(function(r){res(r)})})")
    pg.evaluate("S.locale='hi'; save();")
    voice = pg.evaluate("new Promise(function(res){AIBuild.voiceListen(function(r){res(r)})})")
    ok('hindi voice falls back to typing', voice.get('state')=='unsupported' and 'type' in voice.get('message','').lower())
    pg.evaluate("S.locale='en'; save();")
    bulk = pg.evaluate("""(() => { S.products[0].alt=''; var id=S.products[0].id, price=S.products[0].price, sku=S.products[0].sku; var dry=SelloraPlatform.bulkDryRun(S.products,[id],{alt:'use-name',price:1}); if(dry.ok) return {bad:true}; var preview=SelloraPlatform.bulkDryRun(S.products,[id],{alt:'use-name'}); var applied=SelloraPlatform.bulkApply(S.products,preview); var after=S.products[0].alt; SelloraPlatform.bulkUndo(S.products,applied.undo); return {blocked:!dry.ok, after:after, back:S.products[0].alt, price:S.products[0].price===price, sku:S.products[0].sku===sku}; })()""")
    ok('bulk alt previews and undoes without price or sku', bulk.get('blocked') and bulk.get('after') and bulk.get('back')=='' and bulk.get('price') and bulk.get('sku'), bulk)
    csv = pg.evaluate("""(file) => { var dry=SelloraPlatform.dryRunCsv(file,['tee']); var skip=dry.rows.find(r=>r.action==='skip'); return {skip:!!skip, formula:skip&&skip.title.indexOf(\"'=\")===0, dup:dry.rows.some(r=>r.action==='error'), deleted:dry.deleted}; }""", "Handle,Title\ntee,=1+1\ntee,Second\nnew,Safe\n")
    ok('csv keeps the formula prefix, skips the existing handle, and deletes nothing', csv.get('skip') and csv.get('dup') and csv.get('formula') and csv.get('deleted')==0, csv)
    health = pg.evaluate("""(() => { var h=SelloraPlatform.healthCheck({products:[{id:1,name:'Mug',price:5,desc:'',imgs:['http://169.254.169.254/a']}],menus:[{items:[{url:'/products/missing'}]}]}, null); return {codes:h.findings.map(f=>f.code), browser:h.findings.some(f=>f.verified==='browser')}; })()""")
    ok('health findings are structural and mobile is not called a browser error', 'blocked-link' in health['codes'] and 'broken-link' in health['codes'] and 'mobile-unverified' in health['codes'] and not health['browser'])
    sales = pg.evaluate("""(() => { var r=SelloraPlatform.salesInsights([{demo:true,currency:'USD',total:500,at:1,financial:'paid'},{currency:'USD',total:10,at:1,financial:'paid',fulfillment:'unfulfilled'},{currency:'PKR',total:20,at:1,financial:'pending',fulfillment:'fulfilled'}],{timeZone:'Asia/Karachi',sourceNote:'browser'}); return {count:r.count, usd:r.currencies.USD.total, pkr:r.currencies.PKR.total, sync:r.synchronizedWithServer, few:r.suggestions.some(s=>s.code==='few')}; })()""")
    ok('insights skip demo rows and do not add currencies', sales['count']==2 and sales['usd']==10 and sales['pkr']==20 and sales['sync'] is False and sales['few'])
    pay = pg.evaluate("API.charge({amount:10,cur:'USD',card:{num:'4242424242424242'}})")
    ok('a card charge is not reported as live', pay.get('ok') is False and pay.get('live') is False and 'nothing was charged' in pay.get('error','').lower())
    pg.evaluate("S.locale='en'; save(); location.hash='home'")
    pg.wait_for_timeout(300)
    pg.evaluate("location.hash='setup'")
    pg.wait_for_timeout(300)
    pg.click('#m17healthsum')
    pg.click('#m17health')
    pg.wait_for_timeout(300)
    ok('setup check runs on the signed-in store', pg.locator('#m17findings li').count() > 0)
    os.makedirs('/opt/cursor/artifacts', exist_ok=True)
    pg.screenshot(path='/opt/cursor/artifacts/setup-desktop.png', full_page=False)
    pg.set_viewport_size({'width': 390, 'height': 800})
    pg.wait_for_timeout(200)
    box = pg.locator('#m17next').bounding_box()
    ok('next step fits a phone width', box and box['width'] <= 390)
    ok('no page errors', not errs, errs[:3])
    pg.screenshot(path='/opt/cursor/artifacts/setup-mobile.png', full_page=False)
    b.close()

print('%d/%d passed' % (sum(R), len(R)))
raise SystemExit(0 if all(R) else 1)
