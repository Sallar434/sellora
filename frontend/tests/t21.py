"""Public landing page and onboarding: email → password → verify email → plan → payment (skippable) → goals → welcome home with an editable store name."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vt
from vt import ok
from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    b, pg, errs = vt.launch(p)
    E = pg.evaluate; W = pg.wait_for_timeout
    txt = lambda: E("document.querySelector('#auth').innerText")
    pg.goto(vt.URL); W(700)
    t = txt()
    ok('landing: hero, sign in, free trial', 'Your business starts with VendOm' in t and 'Sign in' in t and 'Start free trial' in t)
    ok('landing: 4 feature cards', pg.locator('.lp-card').count() == 4)
    ok('landing: FAQ answers', pg.locator('.lp-faq details').count() >= 6 and 'How much does VendOm cost?' in t)
    pg.click('.lp-faq details:nth-of-type(3) summary'); W(100)
    ok('FAQ opens on click', E("document.querySelectorAll('.lp-faq details')[2].open"))
    ok('no admin behind the landing page', not pg.locator('aside').is_visible())
    # email from the hero → password step with email locked
    pg.fill('#land-email', 'Sana@Shop.PK'); pg.click('#land-go'); W(300)
    ok('email carried over from the landing page', 'sana@shop.pk' in txt() and pg.locator('#ob-chg').count() == 1)
    pg.fill('#a3', 'short'); W(50)
    ok('8-character rule shown', 'at least 8 characters' in txt())
    pg.click('#ab'); W(150)
    ok('short password refused', '8 characters' in pg.inner_text('#ae'))
    pg.fill('#a3', 'Strong#Pass12'); pg.dispatch_event('#a3', 'input'); W(50)
    ok('strength meter reacts', 'Strong password' in txt() and E("document.querySelector('#ob-bar').className") == 'ok')
    pg.click('#ob-eye'); ok('eye shows the password', E("document.querySelector('#a3').type") == 'text')
    pg.select_option('#a-country', 'United Arab Emirates')
    pg.click('#ab'); W(400)
    ok('welcome email sent on sign-up', E("DB.mail.some(m=>m.to==='sana@shop.pk'&&/Welcome to VendOm/.test(m.subject))"))
    ok('verification email with a 6-digit code', E("DB.mail.some(m=>m.to==='sana@shop.pk'&&/verification code: \\d{6}/.test(m.subject))"))
    ok('verify step', pg.locator('#a-code').count() == 1 and 'sana@shop.pk' in txt())
    pg.fill('#a-code', '12'); pg.click('#ab'); W(100); ok('needs 6 digits', '6-digit' in pg.inner_text('#ae'))
    old = E("DB.ver['sana@shop.pk'].code")
    pg.click('#a-resend'); W(300)
    new = E("DB.ver['sana@shop.pk'].code")
    pg.fill('#a-code', old if old != new else '000000'); pg.click('#ab'); W(100)
    ok('old code stops working after a new one is sent', 'not right' in pg.inner_text('#ae'))
    E("DB.ver['sana@shop.pk'].at=Date.now()-31*60e3")
    pg.fill('#a-code', new); pg.click('#ab'); W(100); ok('expired code refused', 'expired' in pg.inner_text('#ae'))
    pg.click('#a-resend'); W(300)
    # leaving and coming back: an unverified account is sent back to the code step
    pg.reload(); pg.wait_for_load_state('load')
    try: pg.wait_for_selector('#a-code', timeout=8000)
    except Exception: pass
    ok('unverified sign-up resumes at verification', pg.locator('#a-code').count() == 1)
    vt.verify_email(pg, 'sana@shop.pk')
    ok('verified → plan picker', pg.locator('.m13pick').count() == 1 and E("DB.ver['sana@shop.pk'].ok"))
    pg.click('[data-m13p=basic]'); W(300)
    ok('payment step: Basic Rs 300/month after 4 free days', 'Rs 300/month' in txt() and '4 days free' in txt() and pg.locator('#ob-skip').count() == 1)
    pg.click('#ob-chgplan'); W(300); pg.click('[data-iv=annual]'); W(200); pg.click('[data-m13p=grow]'); W(300)
    ok('change plan → Grow yearly', 'Rs 5,760/year' in txt(), txt()[:200])
    pg.fill('#pc-name', 'Sana'); pg.fill('#pc-num', '4242 4242 4242 4241'); pg.fill('#pc-exp', '12/30'); pg.fill('#pc-cvc', '123'); pg.click('#pay-go'); W(100)
    ok('bad card number refused', 'does not look right' in pg.inner_text('#ae'))
    pg.fill('#pc-num', '4242 4242 4242 4242'); pg.fill('#pc-exp', '01/20'); pg.click('#pay-go'); W(100)
    ok('expired card refused', 'expiry' in pg.inner_text('#ae'))
    pg.fill('#pc-exp', '12/30'); pg.click('#pay-go'); W(300)
    ok('card saved (masked) → goals', E("DB.obCard['sana@shop.pk'].last4") == '4242' and 'What can we help you do?' in txt())
    pg.click('[data-goal=whatsapp]'); pg.click('[data-goal=intl]'); pg.click('[data-goal=online]'); W(50)
    ok('chips toggle on and off', E("document.querySelector('[data-goal=online]').getAttribute('aria-pressed')") == 'false')
    pg.click('#ob-back'); W(200); ok('back goes to payment', pg.locator('#pay-go').count() == 1)
    pg.click('#ob-skip'); W(200); pg.click('[data-goal=whatsapp]'); pg.click('[data-goal=intl]'); pg.click('#ab'); W(900)
    ok('store created as "My Store" on the Grow trial', E("[U,S.name,S.sub9.plan,S.sub9.interval]") == ['sana@shop.pk', 'My Store', 'grow', 'annual'])
    ok('goals and country saved', E("S.goals.join()") == 'online,whatsapp,intl' and E("S.country") == 'United Arab Emirates')
    E("location.hash='home'"); W(400)
    h = E("document.querySelector('#main').innerText")
    ok('welcome home', 'Welcome to VendOm' in h and "Let's set up My Store" in h)
    ok('setup cards tailored to goals', 'Turn on WhatsApp orders and COD' in h and 'Sell internationally' in h and 'Add your products' in h)
    pg.click('#home-name'); W(100)
    ok('store name becomes editable', pg.locator('#home-name-in').count() == 1)
    pg.fill('#home-name-in', 'Sana Couture'); pg.press('#home-name-in', 'Enter'); W(400)
    ok('rename saved everywhere', E("S.name") == 'Sana Couture' and "Let's set up Sana Couture" in E("document.querySelector('#main').innerText") and 'Sana Couture' in E("document.querySelector('aside .store b').textContent"))
    pg.click('#home-name'); pg.fill('#home-name-in', 'Nope'); pg.press('#home-name-in', 'Escape'); W(300)
    ok('Escape cancels', E("S.name") == 'Sana Couture')
    pg.click('#home-name'); pg.fill('#home-name-in', '   '); pg.click('#home-name-save'); W(200)
    ok('empty name refused', E("S.name") == 'Sana Couture')
    E("location.hash='home';route()"); W(300)
    pg.click('.ob-sc[data-x="go:apps-whatsapp"]'); W(400)
    ok('setup card opens its page', E("location.hash") == '#apps-whatsapp')
    E("location.hash='home'"); W(300); pg.click('[data-x="obhide"]'); W(300)
    ok('setup guide can be hidden', 'Welcome to VendOm' not in E("document.querySelector('#main').innerText"))
    # phone width
    pg.set_viewport_size({'width': 390, 'height': 844}); E("document.querySelector('#so').click()"); W(500)
    ok('landing fits a phone', E("document.documentElement.scrollWidth") <= 392 and pg.locator('#land-email').is_visible())
    pg.set_viewport_size({'width': 1280, 'height': 800})
    # sign in again
    pg.click('#door-in'); W(200); pg.fill('#a2', 'sana@shop.pk'); pg.fill('#a3', 'Strong#Pass12'); pg.click('#ab'); W(900)
    ok('sign in returns to the store', E("U") == 'sana@shop.pk' and E("S.name") == 'Sana Couture')
    ok('no page errors', not errs, errs)
    b.close()
vt.done()
