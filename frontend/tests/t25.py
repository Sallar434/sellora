"""VendOm Theme Store: browse 120 free themes with filters and pages, open a theme, switch styles and phone view, try and publish it; the live store uses the theme."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vt
from vt import ok, go
from playwright.sync_api import sync_playwright
T = lambda pg, s='#main': pg.evaluate("(document.querySelector(%r)||{}).innerText||''" % s)
with sync_playwright() as p:
    b, pg, errs = vt.launch(p, viewport={'width': 1440, 'height': 1000}); E = pg.evaluate
    vt.signup(pg, email='themes@x.pk', store='Noor Lawn')
    ok('new store starts on a new VendOm theme', E("S.themes.length") == 1 and E("live().v21===1"))
    go(pg, 'themes', 800)
    ok('Themes page shows the current theme and its preview', 'Current theme' in T(pg) and pg.locator('.v21cur .ts-frame .v21').count() == 1)
    ok('menu has Theme store under Online Store', E("NAV_CONFIG.find(n=>n.id==='themes').sub.some(s=>s.id==='theme-store')"))
    pg.click('[data-x="go:theme-store"]'); pg.wait_for_timeout(1500)
    ok('Theme Store lists 120 themes, 24 per page', pg.inner_text('#ts-count') == '1–24 of 120 themes' and pg.locator('.ts-card').count() == 24, pg.inner_text('#ts-count'))
    ok('every theme is free', E("[...document.querySelectorAll('.ts-m span')].every(s=>/^Free/.test(s.textContent))"))
    ok('previews are scaled store pages with photos', E("document.querySelectorAll('.ts-card .v21').length") == 24 and E("[...document.querySelectorAll('.ts-card .ts-in')].every(e=>+e.style.zoom>0.1&&+e.style.zoom<0.5)"))
    pg.wait_for_timeout(1200)
    ok('demo photos load', E("[...document.querySelectorAll('.ts-card img')].slice(0,30).filter(i=>i.complete&&i.naturalWidth>0).length") >= 20)
    pg.click('[data-x="v21pg:2"]'); pg.wait_for_timeout(800)
    ok('page 2', pg.inner_text('#ts-count') == '25–48 of 120 themes')
    pg.check('[data-tsf="ind|Electronics"]'); pg.wait_for_timeout(800)
    n = pg.locator('.ts-card').count()
    ok('industry filter', 0 < n < 24 and E("[...document.querySelectorAll('.ts-card')].every(c=>V21_LIB.find(L=>L.id===c.dataset.tsid).ind.includes('Electronics'))"), n)
    pg.check('[data-tsf="style|Bold"]'); pg.wait_for_timeout(800)
    m = pg.locator('.ts-card').count()
    ok('filters combine', 0 < m <= n)
    pg.click('[data-x="v21clear"]'); pg.wait_for_timeout(800)
    ok('clear filters', pg.inner_text('#ts-count') == '1–24 of 120 themes')
    pg.select_option('#ts-sort', 'az'); pg.wait_for_timeout(800)
    names = E("[...document.querySelectorAll('.ts-m b')].map(b=>b.textContent)")
    ok('sort A–Z', names == sorted(names, key=str.lower), names[:5])
    pg.check('[data-tsf="size|One product"]'); pg.wait_for_timeout(600)
    ok('single-product themes', pg.locator('.ts-card').count() == 4)
    pg.click('[data-tsid="v-beacon"]'); pg.wait_for_timeout(1500)
    ok('theme page opens', E("location.hash") == '#theme-view' and pg.inner_text('#tv-name') == 'Beacon')
    ok('shows details and features', all(w in T(pg) for w in ['Industry', 'Catalog size', 'Fonts', 'Features', 'Free']))
    pg.click('[data-x="v21pal:1"]'); pg.wait_for_timeout(700)
    ok('style switch changes colours', E("document.querySelector('.tv-desk .v21').getAttribute('style').indexOf('--b:#FFFFFF')>=0"))
    pg.click('[data-x="v21dev:mobile"]'); pg.wait_for_timeout(700)
    ok('phone preview fits', pg.locator('.tv-phone .v21').count() == 1 and E("document.querySelector('.tv-phone-in').scrollWidth<=372"), E("document.querySelector('.tv-phone-in').scrollWidth"))
    pg.click('#tv-try'); pg.wait_for_timeout(500)
    ok('Try theme adds it to the library (not live)', E("S.themes.some(t=>t.lib==='v-beacon')") and E("live().lib") != 'v-beacon')
    ok('tried theme keeps the chosen style', E("S.themes.find(t=>t.lib==='v-beacon').bg") == '#FFFFFF')
    go(pg, 'theme-store', 600); pg.click('[data-x="v21clear"]'); pg.wait_for_timeout(600)
    E("ACT.v21open('v-saffron')"); pg.wait_for_timeout(900); pg.click('#tv-pub'); pg.wait_for_timeout(900)
    ok('Publish makes it the live theme', E("live().lib") == 'v-saffron' and E("location.hash") == '#themes')
    ok('library lists the other installed themes', pg.locator('.v21row').count() == 2, pg.locator('.v21row').count())
    E("SF.open('home')"); pg.wait_for_timeout(1200)
    ok('customer store uses the theme', pg.locator('#xsf .v21[data-v21="v-saffron"]').count() == 1 and pg.locator('#xsf .vx').count() == 1)
    ok('store search, currency, account and cart are there', all(pg.locator('#xsf ' + s).count() == 1 for s in ['#xsfs', '#xsfcur', '[data-sf="account"]', '[data-sf="cart"]', '#xsfclose']))
    ok('no demo products in the real store', 'Sunbeam co-ord' not in T(pg, '#xsf') and 'Add products to show them here' in T(pg, '#xsf'))
    pg.fill('#xsfq', 'kurta'); pg.press('#xsfq', 'Enter'); pg.wait_for_timeout(600)
    ok('search works inside the theme', E("SF.state.pg") == 'search')
    E("document.querySelector('#xsfclose').click()"); pg.wait_for_timeout(300)
    E("S.products.push({id:S.nid++,name:'Lawn Kurta',handle:'lawn-kurta',price:35,stock:5,status:'Active',desc:'',cols:[],tags:[],imgs:['demo/p13.webp'],vars:[],opts:[],seo:{},sku:''});save()")
    E("SF.open('home')"); pg.wait_for_timeout(900)
    ok('real products appear in the theme grid', 'Lawn Kurta' in T(pg, '#xsf .vgrid'))
    pg.click('#xsf .vgrid .pc'); pg.wait_for_timeout(700)
    ok('product card opens the product page', E("SF.state.pg") == 'product')
    E("document.querySelector('#xsfclose').click()"); pg.wait_for_timeout(300)
    go(pg, 'themes', 500); E("edit(S.live)"); pg.wait_for_timeout(1200)
    ok('Customize opens the editor with the new sections', all(w in T(pg, 'body') for w in ['Hero banner', 'Header (VendOm)', 'Footer (VendOm)']))
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.goto(vt.URL + '#theme-store'); pg.wait_for_timeout(1500)
    ok('Theme Store fits a phone', E("document.documentElement.scrollWidth<=392") and pg.locator('.ts-card').count() == 24, E("document.documentElement.scrollWidth"))
    E("SF.open('home')"); pg.wait_for_timeout(1000)
    ok('live store fits a phone', E("document.querySelector('#xsf').scrollWidth<=392"), E("document.querySelector('#xsf').scrollWidth"))
    b.close()
vt.done(errs)
