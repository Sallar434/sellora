"""Online Store › Preferences: private mode stays on until a plan is paid; password page; SEO title/description/image in the store's head; hreflang; redirection; spam check; crawler signatures; trusted domains."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vt
from vt import ok, go
from playwright.sync_api import sync_playwright
T = lambda pg, s='#main': pg.evaluate("(document.querySelector(%r)||{}).innerText||''" % s)
with sync_playwright() as p:
    b, pg, errs = vt.launch(p, viewport={'width': 1440, 'height': 1000}); E = pg.evaluate
    pg.context.grant_permissions(['clipboard-read', 'clipboard-write'])
    vt.signup(pg, email='prefs@x.pk', store='Active Reality')
    go(pg, 'online-store-preferences', 800)
    t = T(pg)
    ok('page has every Shopify section', all(w in t for w in ['Store access', 'Private mode', 'Social sharing image and SEO', 'Automatic hreflang tags', 'Automatic redirection', 'Spam protection', 'Crawler access', 'Trusted domains']))
    ok('new store is private with a generated password', E("document.querySelector('#pf-private').checked") and len(pg.input_value('#pf-pw')) == 6)
    ok('during the trial the password cannot be removed', E("document.querySelector('#pf-private').disabled") and 'select a plan' in t)
    pg.fill('#pf-pw', 'miskea'); pg.fill('#pf-msg', 'Opening on Friday')
    ok('password counter', pg.inner_text('#pf-pwc') == '6 of 100 characters used')
    pg.fill('#pf-title', 'Active Reality | Buy Boxing Gloves & Gear, Free Shipping')
    pg.fill('#pf-desc', 'Shop boxing gloves, sparring sets, headgear and groin guards made in Sialkot.')
    ok('title counter and Google preview update live', pg.inner_text('#pf-tc') == '56 of 70 characters used' and 'Boxing Gloves' in pg.inner_text('#pf-gt') and 'Sialkot' in pg.inner_text('#pf-gd'))
    pg.set_input_files('#pf-file', files=[{'name': 'og.png', 'mimeType': 'image/png', 'buffer': open(os.path.join(os.path.dirname(__file__), '..', 'brand', 'vendom-mark-512.png'), 'rb').read()}])
    pg.wait_for_timeout(600)
    ok('social image uploaded and previewed', pg.locator('#pf-shimg img').count() == 1)
    pg.fill('#pf-title', 'Active Reality | Buy Boxing Gloves & Gear, Free Shipping'); pg.fill('#pf-desc', 'Shop boxing gloves, sparring sets, headgear and groin guards made in Sialkot.')
    pg.fill('#pf-pw', 'miskea'); pg.fill('#pf-msg', 'Opening on Friday')
    pg.click('label:has(#pf-rl)'); pg.click('#pf-save'); pg.wait_for_timeout(500)
    ok('preferences saved', E("S.prefs2.title").startswith('Active Reality | Buy') and E("S.online.pw") == 'miskea' and E("S.prefs2.redirLang") is False)
    E("S.online.live=true;S.online.password=false;save()"); go(pg, 'home', 300); go(pg, 'online-store-preferences', 500)
    ok('store forced back to private while unpaid', E("S.online.password===true&&S.online.live===false") and E("document.querySelector('#pf-private').checked"))
    # customer store follows the settings
    E("SF.open('home')"); pg.wait_for_timeout(900)
    ok('store page title and meta description come from Preferences', E("document.title").startswith('Active Reality | Buy') and 'Sialkot' in E("document.querySelector('meta[name=description][data-vsf]').content"))
    ok('social image in og:image', E("document.querySelector('meta[property=\"og:image\"]').content").startswith('data:image/png'))
    ok('private store is marked noindex', E("document.querySelector('meta[name=robots][data-vsf]').content") == 'noindex, nofollow')
    ok('hreflang tags added', E("document.querySelectorAll('link[rel=alternate][hreflang]').length") >= 2)
    ok('owner sees a private notice in the preview', 'Your store is private' in T(pg, '#xsf'))
    pg.click('#pfp-see'); pg.wait_for_timeout(500)
    ok('password page shows the message', 'Opening on Friday' in T(pg, '#xsf') and pg.locator('#pfp-in').count() == 1)
    pg.fill('#pfp-in', 'wrong'); pg.click('#pfp-f button'); pg.wait_for_timeout(200)
    ok('wrong password refused', 'Wrong password' in pg.inner_text('#pfp-e'))
    pg.fill('#pfp-in', 'miskea'); pg.click('#pfp-f button'); pg.wait_for_timeout(500)
    ok('right password opens the store', E("SF.state.pg") == 'home' and pg.locator('#pfp-in').count() == 0)
    E("SF.go('contact')"); pg.wait_for_timeout(400)
    ok('spam check on the contact form', pg.locator('#xsfcontact .pfc-x').count() == 1)
    pg.fill('#xct1', 'Ali'); pg.fill('#xct2', 'ali@x.pk'); pg.fill('#xct4', 'Do you ship to Lahore?')
    n0 = E("(S.inbox||S.contactMsgs||[]).length")
    pg.click('#xsfcontact button[type=submit], #xsfcontact button'); pg.wait_for_timeout(300)
    ok('form blocked until the check is ticked', E("SF.state.pg") == 'contact' and E("(S.inbox||S.contactMsgs||[]).length") == n0)
    E("document.querySelector('#xsfclose').click()"); pg.wait_for_timeout(300)
    ok('admin title restored after closing the store', not E("document.title").startswith('Active Reality | Buy'))
    # crawler access
    go(pg, 'online-store-preferences', 500)
    pg.click('.pf-hrow [data-x="pfsig"]'); pg.wait_for_timeout(200); pg.click('#xok'); pg.wait_for_timeout(200)
    ok('signature needs a name', 'Name the tool' in pg.inner_text('#pfs-e'))
    pg.fill('#pfs-n', 'SEO audit tool'); pg.click('#xok'); pg.wait_for_timeout(1500)
    c = E("S.prefs2.crawlers[0]")
    ok('signature created with the 3 header values', c and c['headers']['Signature-Input'].startswith('sig1=("@authority" "signature-agent");created=') and c['headers']['Signature'].startswith('sig1=:') and 'web-bot-auth' in c['headers']['Signature-Input'], c)
    ok('listed as active', 'SEO audit tool' in T(pg) and 'Active' in T(pg, '.pf-cr'))
    ok('signature verifies with its public key', E("""(async()=>{var c=S.prefs2.crawlers[0];var key=await crypto.subtle.importKey('jwk',{kty:'OKP',crv:'Ed25519',x:c.pub},{name:'Ed25519'},false,['verify']);var par=c.headers['Signature-Input'].slice(5);var base='"@authority": '+'activereality.vendom.app'+'\\n"signature-agent": '+c.headers['Signature-Agent']+'\\n"@signature-params": '+par;var sig=Uint8Array.from(atob(c.headers.Signature.slice(6,-1)),ch=>ch.charCodeAt(0));return crypto.subtle.verify({name:'Ed25519'},key,sig,new TextEncoder().encode(base))})()"""))
    pg.click('[data-x="pftab:expired"]'); pg.wait_for_timeout(300)
    ok('Expired tab is empty', 'Manage crawler access' in T(pg, '.pf-cr'))
    pg.click('[data-x="pftab:all"]'); pg.wait_for_timeout(300)
    pg.click('[data-x^="pfcopy:"][data-x$="|Signature"]'); pg.wait_for_timeout(300)
    ok('copy a value', E("navigator.clipboard.readText()").startswith('sig1=:'))
    pg.click('[data-x^="pfsigx:"]'); pg.wait_for_timeout(300)
    ok('delete a signature', E("S.prefs2.crawlers.length") == 0)
    # trusted domains
    pg.fill('#pf-dom', 'not a domain'); pg.click('[data-x="pfdom"]'); pg.wait_for_timeout(200)
    ok('bad domain refused', 'example.com' in pg.inner_text('#pf-domerr'))
    pg.fill('#pf-dom', 'https://Instagram.com/activereality'); pg.click('[data-x="pfdom"]'); pg.wait_for_timeout(300)
    ok('domain cleaned and added', E("S.prefs2.trusted") == ['instagram.com'])
    E("S.pages[0].b='<p><a href=\"https://unknown-site.example/x\">Size guide</a> <a href=\"https://www.instagram.com/x\">Instagram</a></p>';save()")
    E("SF.open('page:'+S.pages[0].h)"); pg.wait_for_timeout(600)
    pg.click('#xsf a[href^="https://unknown-site"]'); pg.wait_for_timeout(300)
    ok('untrusted link shows a confirmation first', 'leaving' in T(pg, 'body'))
    E("closeM&&closeM()"); E("document.querySelector('#xsfclose').click()"); pg.wait_for_timeout(300)
    # after paying, the password can be removed
    E("S.sub9.status='active';save()"); go(pg, 'home', 200); go(pg, 'online-store-preferences', 500)
    ok('paid: toggle enabled, no plan banner', not E("document.querySelector('#pf-private').disabled") and 'select a plan' not in T(pg))
    pg.click('label:has(#pf-private)'); pg.click('#pf-save'); pg.wait_for_timeout(500)
    ok('paid: store goes public', E("S.online.live===true&&S.online.password===false"))
    E("SF.open('home')"); pg.wait_for_timeout(700)
    ok('public store has no noindex and no private notice', E("!document.querySelector('meta[name=robots][data-vsf]')") and 'Your store is private' not in T(pg, '#xsf'))
    E("document.querySelector('#xsfclose').click()"); pg.wait_for_timeout(200)
    E("S.sub9.status='past_due';save()"); go(pg, 'home', 300)
    ok('plan stops: store is private again', E("S.online.password===true&&S.online.live===false"))
    pg.set_viewport_size({'width': 390, 'height': 844}); go(pg, 'online-store-preferences', 500)
    ok('fits a phone', E("document.documentElement.scrollWidth<=392"), E("document.documentElement.scrollWidth"))
    b.close()
vt.done(errs)
