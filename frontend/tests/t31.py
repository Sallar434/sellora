"""Markets (v51): list with tabs/search, create market with conditions, inherited vs customized settings, validation,
backup region, graph view, catalogs (adjustment, exclusions, fixed prices) that change real store/checkout prices, rollouts."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vt
from vt import ok, go
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b, pg, errs = vt.launch(p, viewport={'width': 1440, 'height': 1000}); E = pg.evaluate
    vt.signup(pg, email='mk@x.pk', store='Noor Lawn')
    E("""(function(){S.rates.EUR=0.92;S.rates.GBP=0.79;
      S.products.push({id:S.nid++,name:'Lawn Kurta',handle:'lawn-kurta',price:100,stock:10,status:'Active',desc:'',cols:[],tags:[],imgs:[],vars:[],opts:[],seo:{}});
      S.products.push({id:S.nid++,name:'Silk Dupatta',handle:'silk-dupatta',price:40,stock:10,status:'Active',desc:'',cols:[],tags:[],imgs:[],vars:[],opts:[],seo:{}});
      save()})()""")
    go(pg, 'markets', 900)
    ok('markets list shows the home market as backup region', 'backup region' in pg.inner_text('#main') and pg.locator('#main tbody tr').count() == 1)
    ok('only one search bar on the list (no generic table tools)', pg.locator('#main input[placeholder*="Search"]').count() == 1)
    pg.click('#mk28new'); pg.wait_for_timeout(700)
    ok('create market opens with an unsaved bar', E("location.hash") == '#market-new' and pg.locator('#mk28ub').is_visible())
    pg.click('#mk28sv'); pg.wait_for_timeout(300)
    ok('name is required', 'name is required' in pg.inner_text('#mk28err'))
    pg.fill('#mk28n', 'Europe'); pg.click('#mk28sv'); pg.wait_for_timeout(300)
    ok('at least one country is required', 'at least one country' in pg.inner_text('#mk28err'))
    pg.click('#mk28cadd'); pg.wait_for_timeout(300)
    pg.fill('#mk28cs', 'germ'); pg.wait_for_timeout(100)
    ok('country search filters the list', E("[...document.querySelectorAll('#mk28cl label')].filter(l=>l.style.display!=='none').length") <= 3)
    for c in ['Germany', 'France']:
        pg.fill('#mk28cs', c); pg.check('#mk28cl input[value="%s"]' % c)
    pg.click('#xok'); pg.wait_for_timeout(500)
    ok('countries show as chips', 'Germany' in pg.inner_text('.mk28chips') and 'France' in pg.inner_text('.mk28chips'))
    ok('multi-country market turns on local currencies by itself', 'Local currencies' in pg.inner_text('#main'))
    ok('no shipping warning while a rest-of-world zone exists', pg.locator('.mk28warn').count() == 0)
    E("window._zs=S.zones;S.zones=S.zones.filter(z=>!z.countries.includes('*')&&!z.countries.includes('France'));route()"); pg.wait_for_timeout(300)
    ok('warns about countries with no shipping rates', pg.locator('.mk28warn').count() == 1 and 'France' in pg.inner_text('.mk28warn'))
    E("S.zones=window._zs;route()"); pg.wait_for_timeout(300)
    pg.click('[data-x="mk28edit:cur"]'); pg.wait_for_timeout(300)
    pg.select_option('#mk28c1', 'EUR'); pg.check('input[name=mk28rt][value=manual]'); pg.fill('#mk28c2', '0.9'); pg.check('#mk28c3'); pg.uncheck('#mk28c4'); pg.click('#xok'); pg.wait_for_timeout(400)
    ok('currency becomes a customized setting', 'Euro' in pg.inner_text('#main') and 'manual rate' in pg.inner_text('#main'))
    pg.click('[data-x="mk28edit:dom"]'); pg.wait_for_timeout(300)
    pg.check('input[name=mk28dk][value=subfolder]'); pg.wait_for_timeout(100); pg.select_option('#mk28dl', 'de'); pg.fill('#mk28dpv', '/de'); pg.click('#xok'); pg.wait_for_timeout(400)
    ok('domain and language customized', '/de' in pg.inner_text('#main') and 'German' in pg.inner_text('#main'))
    pg.click('[data-x="mk28edit:tax"]'); pg.wait_for_timeout(300); pg.check('input[name=mk28tx][value=dynamic]'); pg.check('#mk28dc'); pg.click('#xok'); pg.wait_for_timeout(400)
    ok('duties and taxes customized', 'Dynamic tax display' in pg.inner_text('#main') and 'collect duties' in pg.inner_text('#main'))
    pg.click('#mk28sv'); pg.wait_for_timeout(800)
    mid = E("S.marketsList.find(m=>m.name==='Europe').id")
    ok('market saved', bool(mid) and E("location.hash") == '#market-' + mid and not pg.locator('#mk28ub').is_visible())
    ok('manual rate updates the store rate', E("S.rates.EUR") == 0.9)
    ok('market syncs currency and language for the storefront', E("S.marketsList.find(m=>m.name==='Europe').currency") == 'EUR' and E("S.marketsList.find(m=>m.name==='Europe').lang") == 'de')
    pg.click('[data-x="mk28rm:tax"]'); pg.wait_for_timeout(300)
    ok('removing a customization goes back to inherited and shows the save bar', pg.locator('#mk28ub').is_visible() and 'Tax as a line item' in pg.inner_text('#main'))
    pg.click('[data-x="mk28dis"]'); pg.wait_for_timeout(500)
    ok('discard restores the saved market', 'collect duties' in pg.inner_text('#main'))
    # duplicate active market check
    go(pg, 'market-new', 600); pg.fill('#mk28n', 'Europe copy'); E("window._mk28.countries=['France','Germany']"); pg.click('#mk28sv'); pg.wait_for_timeout(300)
    ok('two active markets cannot have exactly the same countries', 'exactly the same countries' in pg.inner_text('#mk28err'))
    pg.select_option('#mk28st', 'Draft'); pg.click('#mk28sv'); pg.wait_for_timeout(600)
    ok('but it can be saved as a draft', E("S.marketsList.some(m=>m.name==='Europe copy'&&m.status==='Draft')"))
    go(pg, 'market-new', 600); pg.fill('#mk28n', 'europe'); E("window._mk28.countries=['Spain']"); pg.click('#mk28sv'); pg.wait_for_timeout(300)
    ok('market names are unique', 'already called' in pg.inner_text('#mk28err'))
    pg.click('[data-x="mk28dis"]'); pg.wait_for_timeout(400)
    # channel market
    go(pg, 'market-new', 600); pg.click('[data-x="mk28type:channel"]'); pg.wait_for_timeout(300)
    ok('channel market only offers currency and catalogs', pg.locator('[data-x="mk28edit:dom"]').count() == 0 and pg.locator('[data-x="mk28edit:cat"]').count() == 1)
    pg.fill('#mk28n', 'Social'); pg.click('#mk28sv'); pg.wait_for_timeout(300)
    ok('channel market needs a channel', 'sales channel' in pg.inner_text('#mk28err'))
    pg.check('[data-mk28ch="TikTok"]'); pg.click('#mk28sv'); pg.wait_for_timeout(600)
    ok('channel market saved', E("S.marketsList.some(m=>m.type==='channel'&&m.chs.includes('TikTok'))"))
    # list
    go(pg, 'markets', 700)
    ok('list shows 4 markets with types', pg.locator('#main tbody tr').count() == 4 and 'Channel' in pg.inner_text('#main tbody'))
    pg.click('[data-x="mk28tab:draft"]'); pg.wait_for_timeout(300)
    ok('Draft tab filters', pg.locator('#main tbody tr').count() == 1)
    pg.click('[data-x="mk28tab:all"]'); pg.fill('#mk28q', 'euro'); pg.wait_for_timeout(300)
    ok('search filters and keeps focus', pg.locator('#main tbody tr').count() == 2 and E("document.activeElement.id") == 'mk28q')
    pg.fill('#mk28q', '')
    pg.click('#mk28bk'); pg.wait_for_timeout(300); pg.select_option('#mk28bks', 'Japan'); pg.click('#xok'); pg.wait_for_timeout(300)
    ok('backup region must be in an active market', 'isn\'t in an active market' in pg.inner_text('#xme'))
    pg.select_option('#mk28bks', 'France'); pg.click('#xok'); pg.wait_for_timeout(400)
    ok('backup region changes', E("S.backup28") == 'France')
    E("S.backup28=S.country;save()")
    # graph view
    go(pg, 'markets-graph', 700); pg.select_option('#mk28as', 'Germany'); pg.wait_for_timeout(400)
    ok('graph view highlights the matching market', 'Matches Europe' in pg.inner_text('#main') and pg.locator('.mk28node.hit').count() == 1)
    pg.select_option('#mk28as', 'Japan'); pg.wait_for_timeout(400)
    ok('graph view explains the backup region', 'backup region' in pg.inner_text('#main').lower())
    # catalogs
    go(pg, 'markets-catalogs', 600)
    ok('catalogs empty state', 'Create catalog' in pg.inner_text('#main'))
    pg.click('#mk28cnew'); pg.wait_for_timeout(600)
    pg.fill('#ct28t', 'Europe prices'); pg.check('[data-ct28mk="%s"]' % mid)
    pg.select_option('#ct28dir', 'inc'); pg.fill('#ct28adj', '10'); pg.press('#ct28adj', 'Tab'); pg.wait_for_timeout(300)
    pid2 = E("S.products.find(p=>p.name==='Silk Dupatta').id")
    pg.check('[data-ct28s="%d"]' % pid2); pg.wait_for_timeout(200); pg.click('#ct28exb'); pg.wait_for_timeout(300)
    ok('exclude from catalog marks the product', 'Excluded' in pg.inner_text('#main tbody'))
    pg.click('#ct28sv'); pg.wait_for_timeout(700)
    cid = E("S.cat28[0].id")
    ok('catalog saved and assigned to Europe', E("S.marketsList.find(m=>m.name==='Europe').cust.cat.includes(%r)" % cid))
    pid1 = E("S.products.find(p=>p.name==='Lawn Kurta').id")
    ok('Germany price = +10%', E("MK28.price(S.products.find(p=>p.id===%d),'Germany')" % pid1) == 110)
    ok('Pakistan price unchanged', E("MK28.price(S.products.find(p=>p.id===%d),'Pakistan')" % pid1) == 100)
    ok('excluded product unavailable in Germany only', not E("MK28.avail(S.products.find(p=>p.id===%d),'Germany')" % pid2) and E("MK28.avail(S.products.find(p=>p.id===%d),'Pakistan')" % pid2))
    q = E("(function(){var Q=quote([{pid:%d,vi:-1,q:1},{pid:%d,vi:-1,q:1}],{country:'Germany'});return {sub:Q.sub,errs:Q.errs,m:Q.market}})()" % (pid1, pid2))
    ok('checkout uses market price and blocks unavailable products', q['sub'] == 150 and any('not available' in e for e in q['errs']) and q['m'] == 'Europe', q)
    q2 = E("quote([{pid:%d,vi:-1,q:1}],{country:'Pakistan'}).sub" % pid1)
    ok('checkout in Pakistan uses store price', q2 == 100, q2)
    ok('admin prices are not changed by markets', E("PR.vprice(S.products.find(p=>p.id===%d),-1)" % pid1) == 100)
    go(pg, 'catalog-' + cid, 600); pg.fill('[data-ct28p="%d"]' % pid1, '95'); pg.press('[data-ct28p="%d"]' % pid1, 'Tab'); pg.wait_for_timeout(300); pg.click('#ct28sv'); pg.wait_for_timeout(600)
    ok('fixed price overrides the adjustment', E("MK28.price(S.products.find(p=>p.id===%d),'Germany')" % pid1) == 95)
    # storefront in EUR
    E("S.sfCur='EUR';save();SF.open('catalog')"); pg.wait_for_timeout(1000)
    sf = pg.inner_text('#xsf')
    ok('store in EUR hides excluded products', 'Lawn Kurta' in sf and 'Silk Dupatta' not in sf, sf[:300])
    E("document.querySelector('#xsfclose').click();S.sfCur='USD';save()"); pg.wait_for_timeout(300)
    # rollouts
    go(pg, 'catalog-new', 600); pg.fill('#ct28t', 'Flash sale'); pg.select_option('#ct28st', 'Draft'); pg.select_option('#ct28dir', 'dec'); pg.fill('#ct28adj', '20'); pg.press('#ct28adj', 'Tab'); pg.check('[data-ct28mk="%s"]' % mid); pg.click('#ct28sv'); pg.wait_for_timeout(600)
    fid = E("S.cat28.find(c=>c.title==='Flash sale').id")
    go(pg, 'rollout-new', 600); pg.fill('#ro28n', 'Weekend sale'); pg.select_option('#ro28t', 'event'); pg.wait_for_timeout(300)
    pg.click('#ro28add'); pg.wait_for_timeout(300); pg.select_option('[data-ro28i="%s"]' % fid, 'Active'); pg.click('#xok'); pg.wait_for_timeout(400)
    ok('change added and eligibility shows the market', 'Flash sale' in pg.inner_text('#main') and 'Europe' in pg.inner_text('#main'))
    pg.click('#ro28sv'); pg.wait_for_timeout(300)
    ok('event needs an end date', 'needs an end date' in pg.inner_text('#ro28err'))
    E("window._ro28.start=Date.now()-1000;window._ro28.end=Date.now()+3600e3"); pg.click('#ro28sv'); pg.wait_for_timeout(700)
    rid = E("S.ro28[0].id")
    ok('event starts: catalog goes active', E("S.cat28.find(c=>c.id===%r).status" % fid) == 'Active' and E("S.ro28[0].status") == 'Active')
    ok('Germany gets the lower of both catalog prices', E("MK28.price(S.products.find(p=>p.id===%d),'Germany')" % pid1) == 80)
    pg.click('[data-x="ro28end"]'); pg.wait_for_timeout(600)
    ok('ending the event rolls the catalog back to draft', E("S.cat28.find(c=>c.id===%r).status" % fid) == 'Draft' and E("S.ro28[0].status") == 'Ended')
    go(pg, 'markets-rollouts', 600)
    ok('rollouts list shows the ended event', 'Weekend sale' in pg.inner_text('#main') and 'Ended' in pg.inner_text('#main'))
    # delete
    go(pg, 'market-' + mid, 600); pg.click('#mk28mb'); pg.click('[data-x="mk28del"]'); pg.wait_for_timeout(300); pg.click('#xok'); pg.wait_for_timeout(600)
    ok('market deleted', not E("S.marketsList.some(m=>m.id===%r)" % mid) and E("location.hash") == '#markets')
    hm = E("S.marketsList.find(m=>m.countries.includes(S.backup28)).id")
    go(pg, 'market-' + hm, 600); pg.click('#mk28mb'); pg.click('[data-x="mk28del"]'); pg.wait_for_timeout(400)
    ok('cannot delete the market that holds the backup region', E("S.marketsList.some(m=>m.id===%r)" % hm))
    pg.set_viewport_size({'width': 390, 'height': 844}); go(pg, 'markets', 700)
    ok('Markets fits a phone', E("document.documentElement.scrollWidth<=392"), E("document.documentElement.scrollWidth"))
    b.close()
vt.done(errs)
