"""VendOm Autopilot (v61): nav, plan allowances, connections (test mode), day-1 setup (SEO meta, FAQ, blogs, 30-day calendar
with tracked website links, WhatsApp follow-up, ad draft + go-live approvals), skills, approvals, Brand Builder, activity + undo."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vt
from vt import ok, go
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b, pg, errs = vt.launch(p, viewport={'width': 1280, 'height': 900}); E = pg.evaluate
    vt.signup(pg, email='ap41@x.pk', store='Noor Lawn')
    E("""S.products=S.products.filter(p=>0);[['Lawn Kurta',40,'<p>Soft lawn. Breathes well.</p>'],['Silk Dupatta',25,''],['Khussa',30,'Hand made.']].forEach((x,i)=>S.products.push({id:900+i,name:x[0],price:x[1],desc:x[2],stock:20,status:'Active',vars:[],imgs:[],cols:['Clothing']}));save()""")
    go(pg, 'home'); go(pg, 'autopilot-home', 600)
    ok('Autopilot is in the left menu', pg.locator('aside [data-r="autopilot-home"]').count() > 0)
    t = pg.inner_text('#main')
    ok('overview shows plan, test-mode note and setup', 'Autopilot' in t and 'Test mode' in t and 'Day-1 setup' in t, t[:300])
    tier = E("AP38.tier()"); pl = E("AP38.plan()")
    ok('plan allowances are monthly (posts 30/60/90/150)', E("[AP38.plans.starter.posts,AP38.plans.grow.posts,AP38.plans.pro.posts,AP38.plans.scale.posts].join()") == '30,60,90,150')
    pg.fill('#ap38cap', '30000'); pg.click('[data-x="ap38save"]'); pg.wait_for_timeout(300)
    ok('goals saved', E("S.ap38.inputs.cap") == 30000)
    pg.click('#ap38run'); pg.wait_for_timeout(500)
    ok('every product got a meta title and description', E("S.products.every(p=>p.seo&&p.seo.t&&p.seo.d&&p.seo.t.length<=60&&p.seo.d.length<=155)"))
    ok('meta description mentions COD and the store', 'Cash on delivery' in E("S.products[0].seo.d") and 'Noor Lawn' in E("S.products[0].seo.d"))
    ok('FAQ page added for AEO/GEO', E("S.pages.some(p=>p.h==='faq')") and E("S.ap38.faq.length") == 5)
    ok('starter blog drafts created with product links', E("S.blogPosts.filter(b=>b.ap38).length") == min(4, pl['blogs']) and '/products/' in E("S.blogPosts.filter(b=>b.ap38)[0].body"))
    posts = E("S.ap38.cal.filter(c=>c.kind==='post').length"); reels = E("S.ap38.cal.filter(c=>c.kind==='reel').length")
    ok('30-day calendar matches the plan (%s: %s posts, %s reels)' % (tier, posts, reels), posts == pl['posts'] and reels == pl['reels'], (posts, reels, pl))
    ok('every calendar item links to the website with tracking', E("S.ap38.cal.every(c=>c.link.includes('/products/')&&c.link.includes('utm_source=social'))"))
    ok('WhatsApp follow-up switched on', E("S.ap38.wa.cart&&S.ap38.wa.cod"))
    ok('ad campaign waits for approval with a daily budget from the cap', E("S.ap38.appr.some(a=>a.type==='ad'&&a.status==='Waiting'&&a.daily===1000)"))
    go(pg, 'home'); go(pg, 'autopilot-calendar', 500)
    ok('calendar page lists posts with links', 'utm_source=social' in pg.inner_text('#main'))
    go(pg, 'home'); go(pg, 'autopilot-approvals', 500)
    aid = E("S.ap38.appr.find(a=>a.type==='ad').id"); pg.click('[data-x="ap38ok:%s"]' % aid); pg.wait_for_timeout(300)
    ok('approving the ad records it', E("S.ap38.appr.find(a=>a.id==='%s').status" % aid) == 'Approved')
    go(pg, 'home'); go(pg, 'autopilot-connections', 500)
    pg.click('[data-x="ap38conn:whatsapp"]'); pg.wait_for_timeout(300)
    ok('connect works in test mode', E("S.ap38.conn.whatsapp&&S.ap38.conn.whatsapp.mode") == 'test' and 'Connected (test)' in pg.inner_text('#main'))
    ok('higher-plan accounts show an upgrade', tier == 'scale' or pg.locator('#main a.btn[href="#s-plan"]').count() > 0)
    go(pg, 'home'); go(pg, 'autopilot-skills', 500)
    ok('15 skills listed, on by default', pg.locator('[data-ap38skill]').count() == 15 and E("[...document.querySelectorAll('[data-ap38skill]')].every(i=>i.checked)"))
    pg.locator('[data-ap38skill="reel"]').click(); pg.wait_for_timeout(300)
    ok('a skill can be paused', E("S.ap38.skills.reel") is False)
    go(pg, 'home'); go(pg, 'autopilot-brand', 500)
    ok('Brand Builder shows 6 months and Rs 435,000 total', 'Rs 435,000' in pg.inner_text('#main') and pg.locator('#main table tr').count() == 8)
    pg.click('[data-x="ap38brand"]'); pg.wait_for_timeout(300)
    ok('Brand Builder starts at month 1', 'Month 1 of 6' in pg.inner_text('#main'))
    go(pg, 'home'); go(pg, 'autopilot-activity', 500)
    ok('activity log lists the setup work', 'meta titles' in pg.inner_text('#main'))
    pg.locator('[data-x^="ap38undo"]').first.click(); pg.wait_for_timeout(300)
    ok('undo removes the meta tags Autopilot wrote', E("S.products.every(p=>!p.seo.t)"))
    ok('state survives a reload', (pg.reload(), pg.wait_for_timeout(1200), E("S.ap38.cal.length"))[2] > 0)
    vt.done(errs)
